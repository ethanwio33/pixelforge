// The main onboarding screen widget that holds the PageView
class OnboardingScreen extends StatefulWidget {
  const OnboardingScreen({super.key});

  @override
  State<OnboardingScreen> createState() => _OnboardingScreenState();
}

class _OnboardingScreenState extends State<OnboardingScreen>
    with TickerProviderStateMixin {
  late PageController _pageController;
  late AnimationController _animationController;
  int _currentPage = 0;

  // List of onboarding page data
  final List<OnboardingPageData> _onboardingPages = [
    OnboardingPageData(
      title: "AI-Crafted Wallpapers",
      description:
          "Discover a universe of wallpapers generated by cutting-edge AI.",
      child: const GlowingWallpaperPreview(),
    ),
    OnboardingPageData(
      title: "Unique & Personalized",
      description: "Every design is one-of-a-kind, tailored to your style.",
      child: const PersonalizedDesignsMockup(),
    ),
    OnboardingPageData(
      title: "Endless Creativity",
      description: "Explore an infinite gallery that's always growing.",
      child: const AnimatedWallpaperGrid(),
    ),
  ];

  @override
  void initState() {
    super.initState();
    _checkIfFirstTime(); // Check if onboarding should be shown

    _pageController = PageController();
    _animationController = AnimationController(
      vsync: this,
      duration: const Duration(milliseconds: 500),
    );

    _pageController.addListener(() {
      int nextPage = _pageController.page!.round();
      if (_currentPage != nextPage) {
        setState(() {
          _currentPage = nextPage;
        });
        if (_currentPage == _onboardingPages.length - 1) {
          _animationController.forward();
        } else {
          _animationController.reverse();
        }
      }
    });
  }

  // New method to check shared_preferences and navigate if needed
  Future<void> _checkIfFirstTime() async {
    // IMPORTANT: Add shared_preferences to your pubspec.yaml
    // dependencies:
    //   shared_preferences: ^2.0.15
    SharedPreferences prefs = await SharedPreferences.getInstance();
    // Use `true` for testing, `false` for production
    bool seenOnboarding = prefs.getBool('seenOnboarding') ?? false;

    if (seenOnboarding) {
      _navigateToHome();
    }
  }

  void _navigateToHome() {
    // Navigate to your main app screen and remove onboarding from the stack
    Navigator.of(context).pushReplacement(
      MaterialPageRoute(builder: (_) => const AnimeWallpaperApp()),
    );
  }

  // New method to mark onboarding as seen
  Future<void> _completeOnboarding() async {
    SharedPreferences prefs = await SharedPreferences.getInstance();
    await prefs.setBool('seenOnboarding', true);
    _navigateToHome();
  }

  @override
  void dispose() {
    _pageController.dispose();
    _animationController.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      body: SafeArea(
        child: Stack(
          children: [
            PageView.builder(
              controller: _pageController,
              itemCount: _onboardingPages.length,
              itemBuilder: (context, index) {
                return OnboardingPage(
                  data: _onboardingPages[index],
                  currentPage: _currentPage,
                  index: index,
                );
              },
            ),
            Align(
              alignment: Alignment.bottomCenter,
              child: Padding(
                padding: const EdgeInsets.only(bottom: 40.0),
                child: Column(
                  mainAxisSize: MainAxisSize.min,
                  children: [
                    PageIndicator(
                      currentPage: _currentPage,
                      pageCount: _onboardingPages.length,
                    ),
                    const SizedBox(height: 40),
                    FadeTransition(
                      opacity: _animationController,
                      child: GetStartedButton(
                        // Pass the completion function to the button
                        onPressed: _completeOnboarding,
                      ),
                    ),
                  ],
                ),
              ),
            ),
          ],
        ),
      ),
    );
  }
}

// Data model for a single onboarding page
class OnboardingPageData {
  final String title;
  final String description;
  final Widget child;

  OnboardingPageData({
    required this.title,
    required this.description,
    required this.child,
  });
}

// Widget for a single onboarding page content
class OnboardingPage extends StatelessWidget {
  final OnboardingPageData data;
  final int currentPage;
  final int index;

  const OnboardingPage({
    super.key,
    required this.data,
    required this.currentPage,
    required this.index,
  });

  @override
  Widget build(BuildContext context) {
    return Padding(
      padding: const EdgeInsets.symmetric(horizontal: 24.0),
      child: Column(
        mainAxisAlignment: MainAxisAlignment.center,
        children: [
          data.child,
          const SizedBox(height: 60),
          AnimatedOpacity(
            duration: const Duration(milliseconds: 600),
            opacity: currentPage == index ? 1.0 : 0.0,
            child: Text(
              data.title,
              textAlign: TextAlign.center,
              style: const TextStyle(
                fontSize: 26,
                fontWeight: FontWeight.bold,
                color: Colors.white,
                letterSpacing: 0.5,
              ),
            ),
          ),
          const SizedBox(height: 16),
          AnimatedOpacity(
            duration: const Duration(milliseconds: 600),
            opacity: currentPage == index ? 1.0 : 0.0,
            child: Text(
              data.description,
              textAlign: TextAlign.center,
              style: TextStyle(
                fontSize: 16,
                color: Colors.grey[400],
                height: 1.5,
              ),
            ),
          ),
          const SizedBox(height: 120),
        ],
      ),
    );
  }
}

