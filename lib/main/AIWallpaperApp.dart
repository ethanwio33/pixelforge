// 3. Animated Wallpaper Grid for the third screen
class AnimatedWallpaperGrid extends StatefulWidget {
  const AnimatedWallpaperGrid({super.key});

  @override
  State<AnimatedWallpaperGrid> createState() => _AnimatedWallpaperGridState();
}

class _AnimatedWallpaperGridState extends State<AnimatedWallpaperGrid> {
  bool _isAnimated = false;

  @override
  void initState() {
    super.initState();
    // Trigger animation shortly after the widget is built
    WidgetsBinding.instance.addPostFrameCallback((_) {
      if (mounted) {
        setState(() {
          _isAnimated = true;
        });
      }
    });
  }

  @override
  Widget build(BuildContext context) {
    return SizedBox(
      width: 300,
      height: 380,
      child: GridView.builder(
        gridDelegate: const SliverGridDelegateWithFixedCrossAxisCount(
          crossAxisCount: 3,
          crossAxisSpacing: 12,
          mainAxisSpacing: 12,
        ),
        itemCount: 9,
        physics: const NeverScrollableScrollPhysics(),
        itemBuilder: (context, index) {
          // The URL is now created dynamically from your host.
          // index is 0-8, so we add 1 to get image names 1-9.
          final imageUrl =
              'https://www.alhyane.fun/ethanwalkerapps/splash/${index + 1}.jpg';

          return AnimatedContainer(
            duration: Duration(milliseconds: 500 + (index * 100)),
            curve: Curves.easeInOut,
            transform: Matrix4.translationValues(0, _isAnimated ? 0 : 30, 0),
            child: Opacity(
              opacity: _isAnimated ? 1.0 : 0.0,
              child: ClipRRect(
                borderRadius: BorderRadius.circular(12),
                child: Image.network(
                  imageUrl, // Use the new dynamic URL here
                  fit: BoxFit.cover,
                  // Added a loading builder for a better user experience
                  loadingBuilder: (BuildContext context, Widget child,
                      ImageChunkEvent? loadingProgress) {
                    if (loadingProgress == null) return child;
                    return Center(
                      child: CircularProgressIndicator(
                        value: loadingProgress.expectedTotalBytes != null
                            ? loadingProgress.cumulativeBytesLoaded /
                                loadingProgress.expectedTotalBytes!
                            : null,
                        strokeWidth: 2.0,
                        color: Colors.white,
                      ),
                    );
                  },
                  errorBuilder: (context, error, stackTrace) => Container(
                    color: Colors.grey[900],
                    child: const Icon(Icons.error_outline,
                        color: Colors.redAccent),
                  ),
                ),
              ),
            ),
          );
        },
      ),
    );
  }
}
